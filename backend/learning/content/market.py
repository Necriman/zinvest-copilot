"""
"Up or down?" — fifteen real market moments, each cut where the call has to be
made.

Each episode lists anchor points: (position 0..1 along the period, price). The
anchors are the real levels — the peak, the crash, where it ended — taken from
the public record and rounded. The line between them is drawn by `series`:
straight segments plus a small wiggle that is exactly zero at every anchor, so
the known prices stay exact and the path in between looks like a market rather
than a ruler. The screen says the line is smoothed.

The order is deliberately irregular (no up-down-up rhythm to learn), and pairs
of look-alike headlines end opposite ways — March 2020 and September 2008 are
the same story on the day and nothing alike after it. That is the lesson.
"""
import math
import random

BEFORE_POINTS = 42
AFTER_POINTS = 22  # the first one is the decision point itself and is dropped


def series(anchors, points, vol, seed):
    rnd = random.Random(seed)
    noise = [rnd.gauss(0, 1) for _ in range(points)]
    smooth = [(noise[max(0, i - 1)] + noise[i] + noise[min(points - 1, i + 1)]) / 3 for i in range(points)]
    out = []
    for i in range(points):
        x = i / (points - 1)
        for (x0, p0), (x1, p1) in zip(anchors, anchors[1:]):
            if x0 <= x <= x1:
                break
        t = (x - x0) / (x1 - x0) if x1 > x0 else 0.0
        base = p0 + (p1 - p0) * t
        wiggle = smooth[i] * vol * abs(base) * math.sin(math.pi * t)
        out.append(round(base + wiggle, 2))
    return out


def build(episode):
    before = series(episode["before"], BEFORE_POINTS, episode["vol"], episode["slug"] + ":before")
    after = series(episode["after"], AFTER_POINTS, episode["vol"], episode["slug"] + ":after")[1:]
    return before, after


