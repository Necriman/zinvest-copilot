const pick = (value, index) =>
  Array.isArray(value) ? value[index] : Object.fromEntries(Object.entries(value).map(([k, v]) => [k, pick(v, index)]))

export function editorMessages(index) {
  return Object.fromEntries(Object.entries(keys).map(([section, values]) => [section, pick(values, index)]))
}
