function pick(value, index) {
  if (Array.isArray(value)) return value[index]
  return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, pick(v, index)]))
}

export function adminMessages(index) {
  return { admin: pick(keys, index) }
}
